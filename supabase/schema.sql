drop policy if exists "Anyone can submit an appointment" on public.appointments;
create policy "Anyone can submit an appointment"
  on public.appointments
  for insert
  to anon, authenticated
  with check (true);

drop policy if exists "Authenticated admins can view appointments" on public.appointments;
drop policy if exists "Active staff can view appointments" on public.appointments;
create policy "Active staff can view appointments"
  on public.appointments
  for select
  to authenticated
  using (public.is_active_staff());

drop policy if exists "Authenticated admins can update appointments" on public.appointments;
drop policy if exists "Active staff can update appointments" on public.appointments;
create policy "Active staff can update appointments"
  on public.appointments
  for update
  to authenticated
  using (public.is_active_staff())
  with check (public.is_active_staff());

drop policy if exists "Active staff can view staff profiles"
  on public.staff_profiles;
create policy "Active staff can view staff profiles"
  on public.staff_profiles
  for select
  to authenticated
  using (public.is_active_staff());

drop policy if exists "Active staff can view status history"
  on public.appointment_status_history;
create policy "Active staff can view status history"
  on public.appointment_status_history
  for select
  to authenticated
  using (public.is_active_staff());

drop policy if exists "Admins can view operator account history"
  on public.operator_account_history;
create policy "Admins can view operator account history"
  on public.operator_account_history
  for select
  to authenticated
  using (public.is_admin());

